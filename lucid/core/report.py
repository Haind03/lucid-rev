"""Report rendering: Markdown file output and coloured terminal output."""

from __future__ import annotations

from collections import Counter
from collections.abc import Iterable

from lucid import __version__
from lucid.finding import Finding, Severity

MODULE_ORDER = ("triage", "deobfus", "shellcode")
_SEV_STYLE = {
    Severity.INFO: "cyan",
    Severity.LOW: "green",
    Severity.MEDIUM: "yellow",
    Severity.HIGH: "bold red",
}


def _group(findings: Iterable[Finding], modules: Iterable[str]) -> dict[str, list[Finding]]:
    groups: dict[str, list[Finding]] = {m: [] for m in modules}
    for f in findings:
        groups.setdefault(f.module, []).append(f)
    for items in groups.values():
        items.sort(key=lambda f: (-f.severity, f.address if f.address is not None else -1))
    return groups


def _fence(text: str) -> str:
    """Code fence long enough that ``text`` cannot close it early."""
    longest = run = 0
    for ch in text:
        run = run + 1 if ch == "`" else 0
        longest = max(longest, run)
    return "`" * max(3, longest + 1)


def render_markdown(
    findings: list[Finding],
    target: str = "",
    modules: Iterable[str] = MODULE_ORDER,
    status: dict[str, str] | None = None,
) -> str:
    """Render findings as a Markdown report (summary table + one section per module)."""
    status = status or {}
    groups = _group(findings, modules)
    counts = Counter(f.severity for f in findings)

    out: list[str] = [f"# lucid report: `{target or 'unknown'}`", ""]
    out.append(f"_Generated by lucid {__version__} — static analysis only._")
    out += ["", "## Summary", "", "| Severity | Count |", "|---|---|"]
    for sev in sorted(Severity, reverse=True):
        out.append(f"| {sev.name} | {counts.get(sev, 0)} |")
    out.append(f"| **Total** | **{len(findings)}** |")
    out.append("")

    for module, items in groups.items():
        out += [f"## {module}", ""]
        if module in status:
            out += [f"> module {status[module]}", ""]
        if not items:
            out += ["_No findings._", ""]
            continue
        for f in items:
            out += [f"### [{f.severity.name}] {f.title}", ""]
            out.append(f"- **Address:** `{f.address_str}`")
            if f.detail:
                out.append(f"- **Detail:** {f.detail}")
            out.append("")
            if f.evidence:
                fence = _fence(f.evidence)
                out += ["**Evidence:**", "", fence, f.evidence.rstrip("\n"), fence, ""]
    return "\n".join(out).rstrip() + "\n"


def render_terminal(
    findings: list[Finding],
    target: str = "",
    modules: Iterable[str] = MODULE_ORDER,
    status: dict[str, str] | None = None,
    console: object | None = None,
) -> None:
    """Print findings to the terminal with rich, coloured by severity."""
    from rich.console import Console
    from rich.markup import escape
    from rich.panel import Panel
    from rich.table import Table

    con: Console = console if console is not None else Console()  # type: ignore[assignment]
    status = status or {}
    groups = _group(findings, modules)
    counts = Counter(f.severity for f in findings)

    con.rule(f"[bold]lucid {__version__}[/] — {escape(target)}")
    summary = Table(title="Summary", show_header=True, header_style="bold")
    summary.add_column("Severity")
    summary.add_column("Count", justify="right")
    for sev in sorted(Severity, reverse=True):
        summary.add_row(f"[{_SEV_STYLE[sev]}]{sev.name}[/]", str(counts.get(sev, 0)))
    con.print(summary)

    for module, items in groups.items():
        con.rule(f"[bold]{module}[/]", align="left")
        if module in status:
            con.print(f"[dim]module {escape(status[module])}[/]")
        if not items:
            con.print("[dim]No findings.[/]")
            continue
        for f in items:
            style = _SEV_STYLE[f.severity]
            head = f"[{style}][{f.severity.name}][/] {escape(f.title)}  [dim]@ {f.address_str}[/]"
            con.print(head)
            if f.detail:
                con.print(f"    {escape(f.detail)}")
            if f.evidence:
                con.print(Panel(escape(f.evidence.rstrip()), border_style="dim", expand=False))
