"""Report rendering: Markdown, JSON and SARIF files plus coloured terminal output."""

from __future__ import annotations

from collections import Counter
from collections.abc import Iterable

from lucid import __version__
from lucid.finding import Finding, Severity

MODULE_ORDER = ("triage", "deobfus", "shellcode")
_SEV_STYLE = {
    Severity.INFO: "cyan",
    Severity.LOW: "green",
    Severity.MEDIUM: "yellow",
    Severity.HIGH: "bold red",
}


def _group(findings: Iterable[Finding], modules: Iterable[str]) -> dict[str, list[Finding]]:
    groups: dict[str, list[Finding]] = {m: [] for m in modules}
    for f in findings:
        groups.setdefault(f.module, []).append(f)
    for items in groups.values():
        items.sort(key=lambda f: (-f.severity, f.address if f.address is not None else -1))
    return groups


def _fence(text: str) -> str:
    """Code fence long enough that ``text`` cannot close it early."""
    longest = run = 0
    for ch in text:
        run = run + 1 if ch == "`" else 0
        longest = max(longest, run)
    return "`" * max(3, longest + 1)


def render_markdown(
    findings: list[Finding],
    target: str = "",
    modules: Iterable[str] = MODULE_ORDER,
    status: dict[str, str] | None = None,
) -> str:
    """Render findings as a Markdown report (summary table + one section per module)."""
    status = status or {}
    groups = _group(findings, modules)
    counts = Counter(f.severity for f in findings)

    out: list[str] = [f"# lucid report: `{target or 'unknown'}`", ""]
    out.append(f"_Generated by lucid {__version__} — static analysis only._")
    out += ["", "## Summary", "", "| Severity | Count |", "|---|---|"]
    for sev in sorted(Severity, reverse=True):
        out.append(f"| {sev.name} | {counts.get(sev, 0)} |")
    out.append(f"| **Total** | **{len(findings)}** |")
    out.append("")

    for module, items in groups.items():
        out += [f"## {module}", ""]
        if module in status:
            out += [f"> module {status[module]}", ""]
        if not items:
            out += ["_No findings._", ""]
            continue
        for f in items:
            out += [f"### [{f.severity.name}] {f.title}", ""]
            out.append(f"- **Address:** `{f.address_str}`")
            if f.detail:
                out.append(f"- **Detail:** {f.detail}")
            out.append("")
            if f.evidence:
                fence = _fence(f.evidence)
                out += ["**Evidence:**", "", fence, f.evidence.rstrip("\n"), fence, ""]
    return "\n".join(out).rstrip() + "\n"


def render_terminal(
    findings: list[Finding],
    target: str = "",
    modules: Iterable[str] = MODULE_ORDER,
    status: dict[str, str] | None = None,
    console: object | None = None,
) -> None:
    """Print findings to the terminal with rich, coloured by severity."""
    from rich.console import Console
    from rich.markup import escape
    from rich.panel import Panel
    from rich.table import Table

    con: Console = console if console is not None else Console()  # type: ignore[assignment]
    status = status or {}
    groups = _group(findings, modules)
    counts = Counter(f.severity for f in findings)

    con.rule(f"[bold]lucid {__version__}[/] — {escape(target)}")
    summary = Table(title="Summary", show_header=True, header_style="bold")
    summary.add_column("Severity")
    summary.add_column("Count", justify="right")
    for sev in sorted(Severity, reverse=True):
        summary.add_row(f"[{_SEV_STYLE[sev]}]{sev.name}[/]", str(counts.get(sev, 0)))
    con.print(summary)

    for module, items in groups.items():
        con.rule(f"[bold]{module}[/]", align="left")
        if module in status:
            con.print(f"[dim]module {escape(status[module])}[/]")
        if not items:
            con.print("[dim]No findings.[/]")
            continue
        for f in items:
            style = _SEV_STYLE[f.severity]
            head = f"[{style}][{f.severity.name}][/] {escape(f.title)}  [dim]@ {f.address_str}[/]"
            con.print(head)
            if f.detail:
                con.print(f"    {escape(f.detail)}")
            if f.evidence:
                con.print(Panel(escape(f.evidence.rstrip()), border_style="dim", expand=False))


# --------------------------------------------------------------------------- JSON
JSON_SCHEMA = "lucid-report/1"


def render_json(
    findings: list[Finding],
    target: str = "",
    modules: Iterable[str] = MODULE_ORDER,
    status: dict[str, str] | None = None,
    info: dict | None = None,
) -> str:
    """Render findings as a JSON document (schema ``lucid-report/1``)."""
    import json

    status = status or {}
    groups = _group(findings, modules)
    counts = Counter(f.severity for f in findings)
    doc = {
        "schema": JSON_SCHEMA,
        "tool": {"name": "lucid", "version": __version__},
        "target": {"name": target, **(info or {})},
        "summary": {sev.name: counts.get(sev, 0) for sev in sorted(Severity, reverse=True)}
        | {"total": len(findings)},
        "modules": {m: status.get(m, "ok") for m in groups},
        "findings": [f.to_dict() for items in groups.values() for f in items],
    }
    return json.dumps(doc, indent=2, default=str) + "\n"


# -------------------------------------------------------------------------- SARIF
SARIF_SCHEMA = "https://json.schemastore.org/sarif-2.1.0.json"
_SARIF_LEVEL = {
    Severity.HIGH: "error",
    Severity.MEDIUM: "warning",
    Severity.LOW: "note",
    Severity.INFO: "note",
}


def render_sarif(
    findings: list[Finding],
    target: str = "",
    modules: Iterable[str] = MODULE_ORDER,
    status: dict[str, str] | None = None,
    info: dict | None = None,
) -> str:
    """Render findings as a SARIF 2.1.0 log (one run, binary locations by address)."""
    import json

    from lucid.rules import RULES

    status = status or {}
    groups = _group(findings, modules)
    ordered = [f for items in groups.values() for f in items]
    used = sorted({f.rule_id for f in ordered} | {r for r in RULES})
    rule_index = {rid: i for i, rid in enumerate(used)}
    rules = []
    for rid in used:
        rule = RULES.get(rid)
        rules.append({
            "id": rid,
            "name": rule.name if rule else rid.rsplit("/", 1)[-1],
            "shortDescription": {"text": rule.description if rule else rid},
            "defaultConfiguration": {
                "level": _SARIF_LEVEL[rule.severity] if rule else "note"
            },
        })

    artifact_uri = (info or {}).get("path") or target
    results = []
    for f in ordered:
        location: dict = {"physicalLocation": {"artifactLocation": {"uri": artifact_uri}}}
        if f.address is not None:
            location["physicalLocation"]["address"] = {"absoluteAddress": f.address}
        results.append({
            "ruleId": f.rule_id,
            "ruleIndex": rule_index[f.rule_id],
            "level": _SARIF_LEVEL[f.severity],
            "message": {"text": f"{f.title}. {f.detail}".strip()},
            "locations": [location],
            "properties": {
                "severity": f.severity.name,
                "module": f.module,
                "evidence": f.evidence,
                **({"addressHex": f.address_str} if f.address is not None else {}),
                **{f"meta.{k}": v for k, v in f.meta.items()},
            },
        })

    notifications = [
        {"level": "error", "message": {"text": f"module {m}: {msg}"}}
        for m, msg in status.items()
    ]
    log = {
        "$schema": SARIF_SCHEMA,
        "version": "2.1.0",
        "runs": [{
            "tool": {"driver": {
                "name": "lucid",
                "version": __version__,
                "informationUri": "https://github.com/Haind03/lucid-rev",
                "rules": rules,
            }},
            "artifacts": [{
                "location": {"uri": artifact_uri},
                **({"hashes": {"sha-256": info["sha256"]}} if info and "sha256" in info else {}),
            }],
            "invocations": [{
                "executionSuccessful": not status,
                "toolExecutionNotifications": notifications,
            }],
            "results": results,
        }],
    }
    return json.dumps(log, indent=2, default=str) + "\n"
